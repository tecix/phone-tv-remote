android {
    namespace = "io.github.tecix.richtvremote"
    compileSdk = 37

    defaultConfig {
        // Keep the installed ID so updates retain settings, grants and pairing.
        applicationId = "io.github.tecix.textv"
        minSdk = 26
        targetSdk = 36
        versionCode = 3
        versionName = "2.1"
    }

    // Release signing key: keystore.properties (gitignored) next to settings.gradle.kts.
    // Without it, assembleRelease still builds, just unsigned.
    val keystoreFile = rootProject.file("keystore.properties")
    if (keystoreFile.exists()) {
        val props = Properties().apply { keystoreFile.inputStream().use { load(it) } }
        signingConfigs {
            create("release") {
                storeFile = file(props.getProperty("storeFile"))
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            // Release APKs target 64-bit ARM phones only (arm64-v8a / ARMv8).
            ndk { abiFilters += "arm64-v8a" }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            // Screenshots of the screens (ScreenshotTest) land in app/build/outputs/roborazzi.
            all { it.systemProperty("roborazzi.test.record", "true") }
        }
    }
}

